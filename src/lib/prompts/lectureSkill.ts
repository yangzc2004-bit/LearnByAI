export function lectureReviewerRubric() {
  return `# Lecture Reviewer Rubric

请按以下维度审查讲义草稿（这是电子讲义，不是教材）：

1. 聚焦度
   - 是否紧扣本章主题，没有把不相关的概念或后续章节内容塞进来。
   - 是否只讲核心、不追求面面俱到；是否出现偏离主线的冗余小节或内容。

2. 可讲授性
   - 是否像一位老师讲课，而不是教材正文、博客或 AI 回答。
   - 问题导入是否真实具体、能自然引出本章主题。
   - 核心讲解是否直觉先行、必要时才给定义与推导。
   - 典型例子是否完整走通（从问题走到结论）。

3. 重复
   - 是否大段重复上一章或问题导入已讲过的内容。
   - 核心讲解、典型例子、要点整理之间是否互相复述，而不是各有分工。

4. 篇幅失控
   - 篇幅是否明显超出讲义应有的短篇幅，出现教材式的完整推导、大量定义或堆砌例子。
   - 是否为了显厚而注水、为了覆盖而每个点浅尝辄止。
   - 是否出现「定义 / 定理 / 证明 / 章节小结 / 拓展阅读」等教材式段落（讲义体例不要求）。

5. 数学与 Markdown
   - 是否存在未闭合公式或代码块。
   - 独立公式是否使用 $$...$$。
   - 每个重要公式是否解释符号。

6. 语言风格
   - 是否克制、具体、专业。
   - 是否出现营销词、鸡汤、夸张比喻或 AI 腔。
   - 是否存在「重要但不解释为什么」的空话。

7. 概念出处（grounding）
   - 本章引入的命名概念是否是你认识的领域标准术语。
   - 疑似查无出处、可能是生造的概念，要列入 suspectConcepts，并说明为何可疑；正文已给出文献出处的概念不算可疑。

如果发现问题，请输出具体、可执行的修改意见。`;
}
